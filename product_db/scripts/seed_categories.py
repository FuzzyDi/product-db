async def main():
    async with async_session_factory() as db:
        # Проверяем — если уже есть данные, не дублируем
        existing = await db.scalar(select(Category).limit(1))
        if existing:
            print("Категории уже существуют, пропускаем.")
            return

        total = 0

        async def insert(name: str, parent_id: int | None, children: list) -> int:
            nonlocal total
            cat = Category(name=name, parent_id=parent_id)
            db.add(cat)
            await db.flush()
            total += 1
            for child_name, grandchildren in children:
                await insert(child_name, cat.id, grandchildren)
            return cat.id

        for root_name, root_children in TREE:
            await insert(root_name, None, root_children)

        await db.commit()
        print(f"Добавлено {total} категорий.")


if __name__ == "__main__":
    asyncio.run(main())
