async def main():
    async with AsyncSessionLocal() as db:
        result = await db.execute(select(ProductType))
        types = result.scalars().all()

        updated = 0
        missing = []
        for pt in types:
            uz = UZ_NAMES.get(pt.name_ru)
            if uz:
                pt.name_uz_latn, pt.name_uz_cyrl = uz
                updated += 1
            else:
                missing.append(pt.name_ru)

        await db.commit()
        print(f"Обновлено: {updated} типов товаров.")
        if missing:
            print(f"Без перевода ({len(missing)}):")
            for m in sorted(missing):
                print(f"  - {m}")


if __name__ == "__main__":
    asyncio.run(main())
